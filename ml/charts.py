def chart_rule_vs_model(metrics: dict) -> None:
    """
    The central result: which technique wins on which defect class.

    Grouped bars rather than a table because the reversal between the two panels is the
    finding, and a reversal is easier to see than to read.
    """
    fig, axes = plt.subplots(1, 2, figsize=(12, 5), sharey=True)

    panels = [
        ("CORRUPT_QUANTITY", "Corrupt quantity — absolute violation",
         "quantity > 1e6 is exact. The model is strictly worse here."),
        ("CONTEXTUAL_PRICE", "Contextual price — relative violation",
         "No global threshold fits a catalogue of washers and pumps."),
    ]
    names = {
        "sql_rule_quantity_gt_1e6": "SQL rule\nquantity > 1e6",
        "sql_rule_unit_cost_p99.9": "SQL rule\nunit_cost p99.9",
        "isolation_forest": "Isolation\nForest",
    }

    for ax, (defect, title, sub) in zip(axes, panels):
        data = metrics["by_class"][defect]
        keys = list(names.keys())
        x = np.arange(len(keys))
        width = 0.27

        prec = [data[k]["precision"] for k in keys]
        rec = [data[k]["recall"] for k in keys]
        f1 = [data[k]["f1"] for k in keys]

        ax.bar(x - width, prec, width, label="precision", color=BLUE)
        ax.bar(x, rec, width, label="recall", color=GREEN)
        ax.bar(x + width, f1, width, label="F1", color=AMBER)

        for xi, vals in zip(x, zip(prec, rec, f1)):
            for off, v in zip((-width, 0, width), vals):
                if v > 0.02:
                    ax.text(xi + off, v + 0.02, f"{v:.2f}", ha="center",
                            color=TEXT, fontsize=8)

        ax.set_xticks(x)
        ax.set_xticklabels([names[k] for k in keys], fontsize=9)
        ax.set_ylim(0, 1.15)
        _style(ax, title, sub)

    axes[0].set_ylabel("score")
    axes[0].legend(facecolor=PANEL, edgecolor=GRID, labelcolor=TEXT,
                   framealpha=0.9, loc="upper right")
    fig.suptitle("Rules and models are not interchangeable",
                 color=TEXT, fontsize=15, fontweight="bold", x=0.09, ha="left", y=1.04)
    _save(fig, "ml_rule_vs_model.png")


