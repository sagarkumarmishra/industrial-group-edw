def chart_score_distribution(scored: pd.DataFrame, metrics: dict) -> None:
    """
    Anomaly score distribution, clean against defective, with the threshold drawn on.

    A log y-axis is essential rather than decorative. There are 199,500 clean rows and 162
    contextual anomalies; on a linear scale the anomalies are invisible, which is exactly
    the problem the chart exists to illustrate.
    """
    fig, ax = plt.subplots(figsize=(10, 5))

    clean = scored.loc[scored["defect_type"] == "CLEAN", "anomaly_score"]
    price = scored.loc[scored["defect_type"] == "CONTEXTUAL_PRICE", "anomaly_score"]
    qty = scored.loc[scored["defect_type"] == "CORRUPT_QUANTITY", "anomaly_score"]

    bins = np.linspace(scored["anomaly_score"].min(), scored["anomaly_score"].max(), 90)
    ax.hist(clean, bins=bins, color=BLUE, alpha=0.75, label=f"clean ({len(clean):,})")
    ax.hist(price, bins=bins, color=AMBER, alpha=0.95,
            label=f"contextual price ({len(price)})")
    ax.hist(qty, bins=bins, color=RED, alpha=0.95,
            label=f"corrupt quantity ({len(qty)})")

    thr = metrics["score_threshold"]
    ax.axvline(thr, color=PURPLE, linestyle="--", linewidth=1.6)
    ax.text(thr, ax.get_ylim()[1] * 0.45, f"  threshold\n  {thr:.3f}",
            color=PURPLE, fontsize=9, va="top")

    ax.set_yscale("log")
    ax.set_xlabel("isolation forest anomaly score  (higher = more anomalous)")
    ax.set_ylabel("rows  (log scale)")
    _style(ax, "Anomaly scores separate contextual price defects from clean rows",
           "Log scale, because 162 anomalies against 199,500 clean rows are otherwise "
           "invisible -- which is the whole problem")
    ax.legend(facecolor=PANEL, edgecolor=GRID, labelcolor=TEXT, framealpha=0.9)
    _save(fig, "ml_score_distribution.png")


