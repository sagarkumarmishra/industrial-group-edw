"""
Generates every chart in docs/assets/ from the live outputs of the ML pipeline.

Nothing here is drawn by hand or copied from a previous run. Each figure reads the parquet
and json that ml/detect_anomalies.py and ml/volume_monitor.py just wrote, so a chart in the
README cannot silently disagree with the numbers in the text -- if a metric moves, the
picture moves with it on the next run.

That is a deliberate choice about trust. A screenshot pasted into a README is unverifiable
and ages badly; a chart regenerated by `make charts` is neither.

Usage:
    python -m ml.charts
"""
from __future__ import annotations

import json
import os

import matplotlib
matplotlib.use("Agg")           # no display on CI or a headless box

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.ticker import FuncFormatter

ML_DIR = os.path.join("data", "ml")
OUT_DIR = os.path.join("docs", "assets")

# Palette. Dark slate background with a small number of saturated accents, chosen for
# legibility against both light and dark GitHub themes -- a chart that vanishes in dark mode
# is a chart nobody looks at.
BG = "#0d1117"
PANEL = "#161b22"
GRID = "#30363d"
TEXT = "#e6edf3"
MUTED = "#8b949e"
BLUE = "#58a6ff"
GREEN = "#3fb950"
AMBER = "#d29922"
RED = "#f85149"
PURPLE = "#bc8cff"

plt.rcParams.update({
    "figure.facecolor": BG,
    "axes.facecolor": PANEL,
    "savefig.facecolor": BG,
    "text.color": TEXT,
    "axes.labelcolor": TEXT,
    "axes.edgecolor": GRID,
    "xtick.color": MUTED,
    "ytick.color": MUTED,
    "grid.color": GRID,
    "font.size": 10,
    "axes.titlesize": 13,
    "axes.titleweight": "bold",
    "figure.dpi": 130,
})


def _style(ax, title: str, subtitle: str = "") -> None:
    ax.set_title(title, color=TEXT, pad=18 if subtitle else 10, loc="left")
    if subtitle:
        ax.text(0.0, 1.02, subtitle, transform=ax.transAxes,
                color=MUTED, fontsize=9, va="bottom")
    ax.grid(True, alpha=0.25, linewidth=0.6)
    ax.set_axisbelow(True)
    for spine in ("top", "right"):
        ax.spines[spine].set_visible(False)


def _save(fig, name: str) -> str:
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, name)
    fig.savefig(path, bbox_inches="tight", pad_inches=0.3)
    plt.close(fig)
    size = os.path.getsize(path) / 1024
    print(f"  {name:<34}{size:>7.0f} KB")
    return path


