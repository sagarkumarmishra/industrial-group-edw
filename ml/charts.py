def chart_unit_trap(db_path: str = os.path.join("data", "edw.duckdb")) -> None:
    """
    Trap 2, the mixed time units, shown as reported hours before and after the fix.

    This is the most expensive trap in the project and the least visible: work_hours is
    sometimes booked in seconds, with the unit in a separate column. Missing it inflates
    labour by 3,600x on the affected rows, and the total still looks like a number.
    """
    import duckdb

    con = duckdb.connect(db_path, read_only=True)
    df = con.execute(
        """
        select
            c.company_name,
            sum(t.work_hours)             as correct_hours,
            -- The naive figure needs no arithmetic at all: it is simply the as-sourced
            -- column summed, mixing seconds and hours in one total. That is precisely
            -- how the mistake happens in practice -- nobody computes anything wrong,
            -- they just SUM the column that was already there.
            sum(t.work_hours_as_sourced)  as naive_hours,
            sum(t.was_unit_converted)     as rows_in_seconds
        from main_marts.fct_labour_hours t
        join main_marts.dim_company c on t.company_key = c.company_key
        where t.is_deleted = 0
        group by 1
        order by 2 desc
        """
    ).df()
    con.close()

    fig, ax = plt.subplots(figsize=(11, 5.5))
    x = np.arange(len(df))
    width = 0.38

    ax.bar(x - width / 2, df["naive_hours"], width,
           color=RED, alpha=0.9, label="if the unit column is ignored")
    ax.bar(x + width / 2, df["correct_hours"], width,
           color=GREEN, label="after converting seconds to hours")

    ax.set_yscale("log")
    ax.set_xticks(x)
    ax.set_xticklabels([n[:22] for n in df["company_name"]], fontsize=9,
                       rotation=18, ha="right")
    ax.set_ylabel("total labour hours  (log scale)")
    ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:,.0f}"))

    worst = (df["naive_hours"] / df["correct_hours"]).max()
    _style(ax, "Trap 2 — the same query, reported two ways",
           f"Ignoring one unit column overstates labour by up to {worst:,.0f}x. "
           "Both totals look plausible in isolation.")
    ax.legend(facecolor=PANEL, edgecolor=GRID, labelcolor=TEXT, framealpha=0.9)
    _save(fig, "trap_unit_conversion.png")


def main() -> None:
    print("Generating charts from the live pipeline outputs")
    print("-" * 46)

    scored = pd.read_parquet(os.path.join(ML_DIR, "scored_transactions.parquet"))
    pr = pd.read_parquet(os.path.join(ML_DIR, "pr_curve.parquet"))
    daily = pd.read_parquet(os.path.join(ML_DIR, "daily_volume.parquet"))
    with open(os.path.join(ML_DIR, "metrics.json"), encoding="utf-8") as fh:
        metrics = json.load(fh)

    chart_score_distribution(scored, metrics)
    chart_rule_vs_model(metrics)
    chart_pr_curve(pr, metrics)
    chart_volume_monitor(daily)
    chart_unit_trap()

    print("-" * 46)
    print(f"Wrote 5 charts to {OUT_DIR}")
    print("\nNext:  python -m docs.build_report_pdf")


if __name__ == "__main__":
    main()
