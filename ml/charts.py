def chart_pr_curve(pr: pd.DataFrame, metrics: dict) -> None:
    """
    Precision-recall curve with all three candidate operating points marked.

    PR rather than ROC: at a 0.08% positive rate, ROC looks flattering because the false
    positive rate is diluted by 199,500 easy negatives. PR does not let you hide that.
    """
    fig, ax = plt.subplots(figsize=(9, 6))

    ax.plot(pr["recall"], pr["precision"], color=BLUE, linewidth=2,
            label="isolation forest")

    price = metrics["by_class"]["CONTEXTUAL_PRICE"]
    ops = metrics["operating_points_contextual_price"]
    rule = price["sql_rule_unit_cost_p99.9"]

    points = [
        (rule["recall"], rule["precision"], RED, "o",
         f"SQL rule p99.9  (F1 {rule['f1']:.2f})"),
        (price["isolation_forest"]["recall"], price["isolation_forest"]["precision"],
         AMBER, "s", f"contamination {metrics['contamination']}  "
                     f"(F1 {price['isolation_forest']['f1']:.2f})"),
        (ops["best_f1_oracle"]["recall"], ops["best_f1_oracle"]["precision"],
         PURPLE, "D", f"best F1, oracle-tuned  (F1 {ops['best_f1_oracle']['f1']:.2f})"),
        (ops["alert_budget"]["recall"], ops["alert_budget"]["precision"],
         GREEN, "*", f"top-{ops['alert_budget']['budget']} alert budget  "
                     f"(precision {ops['alert_budget']['precision']:.2f})"),
    ]
    for r, p, colour, marker, label in points:
        ax.scatter([r], [p], color=colour, s=190 if marker == "*" else 110,
                   marker=marker, zorder=5, edgecolors=BG, linewidths=1.2, label=label)

    ap = price["isolation_forest"]["average_precision"]
    ax.set_xlabel("recall")
    ax.set_ylabel("precision")
    ax.set_xlim(-0.02, 1.02)
    ax.set_ylim(-0.02, 1.05)
    _style(ax, f"Contextual price anomalies — average precision {ap:.3f}",
           "Four thresholds on one curve. Only the green star can be chosen without "
           "already knowing the answers.")
    ax.legend(facecolor=PANEL, edgecolor=GRID, labelcolor=TEXT,
              framealpha=0.9, loc="lower left", fontsize=9)
    _save(fig, "ml_pr_curve.png")


