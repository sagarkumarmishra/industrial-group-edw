def chart_volume_monitor(daily: pd.DataFrame) -> None:
    """
    Daily row counts per subsidiary with the outage and spike marked.

    The outage is the point of the figure: three days at exactly zero for one company,
    which every row-level test in the project reports as healthy.

    Daily counts over 900 days are visually noisy, so incidents are highlighted with a
    full-height band rather than left to be spotted among the noise. A monitoring chart
    that requires squinting is not a monitoring chart.
    """
    companies = (
        daily[["company_key", "company_name"]]
        .drop_duplicates()
        .sort_values("company_key")
    )
    n = len(companies)

    fig, axes = plt.subplots(n, 1, figsize=(13, 1.75 * n), sharex=True)
    if n == 1:
        axes = [axes]

    for ax, (_, row) in zip(axes, companies.iterrows()):
        grp = daily[daily["company_key"] == row["company_key"]].sort_values("txn_date")

        drops = grp[(grp["is_anomaly"]) & (grp["direction"] == "DROP")]
        spikes = grp[(grp["is_anomaly"]) & (grp["direction"] == "SPIKE")]

        # Full-height bands first, so they sit behind the series.
        #
        # np.timedelta64 with an explicit unit rather than pd.Timedelta: this pandas build
        # routes every Timedelta construction through a generic numpy timedelta, which numpy
        # now deprecates. Being explicit about the unit sidesteps it and is clearer anyway.
        half = np.timedelta64(2, "D")
        for _, d in drops.iterrows():
            centre = pd.Timestamp(d["txn_date"])
            ax.axvspan(centre - half, centre + half, color=RED, alpha=0.22, zorder=0)
        for _, s in spikes.iterrows():
            centre = pd.Timestamp(s["txn_date"])
            ax.axvspan(centre - half, centre + half, color=AMBER, alpha=0.22, zorder=0)

        ax.plot(grp["txn_date"], grp["row_count"], color=BLUE,
                linewidth=0.5, alpha=0.5, zorder=2)
        ax.plot(grp["txn_date"], grp["expected"], color=TEXT,
                linewidth=1.3, alpha=0.85, zorder=3)

        ax.scatter(drops["txn_date"], drops["row_count"], color=RED, s=42,
                   zorder=6, edgecolors=BG, linewidths=0.7)
        ax.scatter(spikes["txn_date"], spikes["row_count"], color=AMBER, s=42,
                   zorder=6, edgecolors=BG, linewidths=0.7)

        # Company name inside the panel, which reads better than a rotated axis label.
        verdict = ""
        if not drops.empty:
            verdict += f"   {len(drops)} DROP"
        if not spikes.empty:
            verdict += f"   {len(spikes)} SPIKE"
        ax.text(0.006, 0.88, row["company_name"], transform=ax.transAxes,
                fontsize=9, fontweight="bold",
                color=TEXT if verdict else MUTED, va="top")
        if verdict:
            ax.text(0.006, 0.60, verdict.strip(), transform=ax.transAxes, fontsize=8.5,
                    color=RED if not drops.empty else AMBER, va="top", fontweight="bold")

        ax.grid(True, alpha=0.15, linewidth=0.5)
        ax.set_axisbelow(True)
        for spine in ("top", "right"):
            ax.spines[spine].set_visible(False)
        ax.tick_params(labelsize=8)
        ax.set_ylim(bottom=-4)

        zeroes = drops[drops["row_count"] == 0]
        if not zeroes.empty:
            first = zeroes.iloc[0]
            ax.annotate(
                f"extract never ran — {len(zeroes)} days at 0 rows",
                xy=(first["txn_date"], 0),
                xytext=(-210, 26), textcoords="offset points",
                color=RED, fontsize=8.5, fontweight="bold",
                arrowprops=dict(arrowstyle="->", color=RED, lw=1.2),
            )
        if not spikes.empty:
            worst = spikes.loc[spikes["row_count"].idxmax()]
            ax.annotate(
                f"extract ran twice — {worst['row_count']:.0f} rows vs "
                f"{worst['expected']:.0f} expected",
                xy=(worst["txn_date"], worst["row_count"]),
                xytext=(-250, -12), textcoords="offset points",
                color=AMBER, fontsize=8.5, fontweight="bold",
                arrowprops=dict(arrowstyle="->", color=AMBER, lw=1.2),
            )

    fig.suptitle("Daily transaction volume per subsidiary",
                 color=TEXT, fontsize=14, fontweight="bold",
                 x=0.075, ha="left", y=0.997)
    fig.text(0.075, 0.9655,
             "White line is the 28-day rolling median. Every one of the 70 dbt tests "
             "passes on all 5,400 of these company-days, including the three at zero.",
             color=MUTED, fontsize=9, ha="left")
    axes[-1].set_xlabel("transaction date")
    fig.subplots_adjust(top=0.938, hspace=0.12)
    _save(fig, "ml_volume_monitor.png")


